async function seedPlayers() {
  console.log('Upserting players (idempotent)...');

  const allTeams = await prisma.team.findMany();
  const teamMap = new Map(allTeams.map((t) => [t.code, t.id]));

  type P = { id: string; name: string; position: string; teamCode: string };

  const allPlayers: P[] = [
    ...getGrupoA(), // MEX | RSA | KOR | CZE
    ...getGrupoB(), // CAN | BIH | QAT | SUI
    ...getGrupoC(), // BRA | MAR | HAI | SCO
    ...getGrupoD(), // USA | PAR | AUS | TUR
    ...getGrupoE(), // GER | CUW | CIV | ECU
    ...getGrupoF(), // NED | JPN | SWE | TUN
    ...getGrupoG(), // BEL | EGY | IRN | NZL
    ...getGrupoH(), // ESP | CPV | KSA | URY
    ...getGrupoI(), // FRA | SEN | IRQ | NOR
    ...getGrupoJ(), // ARG | ALG | AUT | JOR
    ...getGrupoK(), // POR | COL | UZB | COD
    ...getGrupoL(), // ENG | CRO | GHA | PAN
  ];

  for (const p of allPlayers) {
    const teamId = teamMap.get(p.teamCode);
    if (teamId) {
      await prisma.player.upsert({
        where: { id: p.id },
        update: { name: p.name, position: p.position, teamId },
        create: { id: p.id, name: p.name, position: p.position, teamId },
      });
    }
  }
  console.log(`Players seeded/updated: ${allPlayers.length} total.`);
}

